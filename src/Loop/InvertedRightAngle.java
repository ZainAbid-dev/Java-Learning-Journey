package Loop;

public class InvertedRightAngle {
   public static void main(String[] args) {
       // Inverted  Right Angle Triangle
       for(int i = 4; i >= 0; i--){
           for(int j = i ; j >= 0; j--){
               System.out.print("* ");
           }
           System.out.println();
       }

    }
}
